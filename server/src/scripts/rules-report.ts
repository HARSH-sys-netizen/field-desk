/**
 * Renders the rulebook as plain-language Markdown and counts scenarios
 * from the same declarations, so the readable rules cannot drift from the
 * enforced ones. Usage: pnpm rules:report
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ROLES } from '@crm/shared';
import { RULEBOOK } from '../rules/rulebook.js';
import { REACTIONS } from '../rules/reactions.js';
import { allowedStates } from '../rules/guards.js';
import { ENTITY_STATES, type Area, type Entity } from '../rules/rule.js';

const label = (value: string) =>
  value
    .toLowerCase()
    .replaceAll('_', ' ')
    .replace(/^./, (c) => c.toUpperCase());
const roleName: Record<string, string> = {
  SALES: 'Sales',
  KAM: 'KAM',
  WAREHOUSE: 'Warehouse',
  ACCOUNTS: 'Accounts',
  ADMIN: 'Admin',
};

export function scenarioCounts() {
  const entities = Object.keys(ENTITY_STATES) as Entity[];
  const product = entities.reduce(
    (total, entity) => total * ENTITY_STATES[entity].length,
    1,
  );
  const actions = Object.entries(RULEBOOK);
  const naive = ROLES.length * actions.length * product;
  const rows = actions.map(([type, rule]) => {
    const allowed = allowedStates(rule.when);
    const valid = rule.reads.reduce(
      (total, entity) =>
        total * (allowed[entity]?.length ?? ENTITY_STATES[entity].length),
      1,
    );
    return { type, actors: rule.who.length + 1, valid };
  });
  const pruned = rows.reduce((total, row) => total + row.valid, 0);
  const prunedWithActors = rows.reduce(
    (total, row) => total + row.valid * row.actors,
    0,
  );
  return { entities, product, naive, rows, pruned, prunedWithActors };
}

export function renderRulebook() {
  const lines: string[] = [
    '# FieldDesk rulebook',
    '',
    '> Generated by `pnpm rules:report` from `server/src/rules/rulebook.ts`. Do not edit by hand.',
    '',
    'Read each row as: **who** may **do this** when **every condition holds**; then **what follows** happens automatically. Admin may do everything. Quantity and money limits (for example "cannot deliver more than was dispatched") are checked by the domain models and named in the rule column.',
    '',
  ];
  const areas: Area[] = [
    'Customers',
    'Orders',
    'Fulfillment',
    'Accounts',
    'Credits',
    'Rewards',
  ];
  for (const area of areas) {
    lines.push(`## ${area}`, '');
    lines.push(
      '| Action | Who | Allowed when | What follows | Rules |',
      '| --- | --- | --- | --- | --- |',
    );
    for (const [type, rule] of Object.entries(RULEBOOK)) {
      if (rule.area !== area) continue;
      const when = rule.when.length
        ? rule.when.map((g) => `${g.says} (${g.rule})`).join('; ')
        : 'Always, within the quantity and amount limits';
      const follows =
        rule.allocates === 'own account'
          ? "Free cash is allocated to the oldest open charges on the customer's account (WF-002)"
          : rule.allocates === 'receiving account'
            ? 'Free cash is allocated to the oldest open charges on the receiving account (WF-002)'
            : '—';
      lines.push(
        `| **${label(type)}** — ${rule.does} | ${rule.who.map((r) => roleName[r]).join(', ')} | ${when} | ${follows} | ${rule.cites.join(', ')} |`,
      );
    }
    lines.push('');
  }
  lines.push('## Automatic follow-ups', '');
  for (const reaction of Object.values(REACTIONS))
    lines.push(
      `- **${reaction.says}** (${reaction.rule}). Runs when ${reaction.trigger}.`,
    );
  const counts = scenarioCounts();
  lines.push(
    '',
    '## Scenario count',
    '',
    'Computed from the same declarations, using the formulas in the assignment brief.',
    '',
    `- Entities and states: ${counts.entities.map((e) => `${e} (${ENTITY_STATES[e].length})`).join(', ')} → ∏ sᵢ = ${counts.product}.`,
    `- Naive: ${ROLES.length} roles × ${counts.rows.length} actions × ${counts.product} = **${counts.naive.toLocaleString('en-IN')}**.`,
    `- Pruned, Σₐ |Vₐ restricted to Rₐ| (only the entities each action reads, only the states its guards allow): **${counts.pruned}**.`,
    `- Pruned, also multiplied by the roles allowed per action (Admin included): **${counts.prunedWithActors}**.`,
    '',
    'Quantity and amount checks prune further but are not states, so they are not counted.',
    '',
    '| Action | Reads | Valid state combinations |',
    '| --- | --- | --- |',
    ...counts.rows.map((row) => {
      const rule = RULEBOOK[row.type as keyof typeof RULEBOOK];
      return `| ${label(row.type)} | ${rule.reads.join(', ') || '—'} | ${row.valid} |`;
    }),
    '',
  );
  return lines.join('\n');
}

if (process.argv[1]?.endsWith('rules-report.js')) {
  const target = resolve(process.argv[2] ?? '../docs/solution/rulebook.md');
  writeFileSync(target, renderRulebook());
  const counts = scenarioCounts();
  console.log(
    `Wrote ${target}. Naive ${counts.naive}; pruned ${counts.pruned} (${counts.prunedWithActors} with actors).`,
  );
}
